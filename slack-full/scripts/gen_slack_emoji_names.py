#!/usr/bin/env python3
"""Generate slack-full/adapter/slack_emoji_names.go from Slack's emoji-data.

Usage: gen_slack_emoji_names.py <emoji.json> <source commit> <out.go>

<emoji.json> is iamcal/emoji-data's emoji.json (the table Slack publishes and
its clients use): every entry's short_names are the colon shortcodes Slack
stores for that emoji. The adapter's publish read-back folds a shortcode out
of the compare only when its name is in this table (gf-pu2 finding 3d), so
the table is regenerated, never edited by hand.
"""
import json
import re
import sys

NAME = re.compile(r"^[a-z0-9_+\-]+$")


def main(argv):
    if len(argv) != 4:
        sys.stderr.write(__doc__)
        return 2
    src, commit, out = argv[1], argv[2], argv[3]
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    names = set()
    for entry in data:
        for name in entry.get("short_names", []):
            if not NAME.match(name):
                raise SystemExit(f"short name {name!r} is outside the shortcode alphabet")
            names.add(name)
    lines = [
        "// Code generated by slack-full/scripts/gen_slack_emoji_names.py; DO NOT EDIT.",
        "//",
        "// Source: iamcal/emoji-data emoji.json at commit " + commit + ",",
        "// the emoji table Slack publishes; every entry's short_names are the colon",
        "// shortcodes Slack stores for that emoji (" + str(len(names)) + " names from " + str(len(data)) + " entries).",
        "",
        "package main",
        "",
        "// slackStandardEmojiNames is the sorted set of Slack's standard emoji",
        "// shortcode names: the one source of truth for what a `:name:` token in a",
        "// stored message is (slackIsStandardEmojiName, slackFoldEmojiProse).",
        "var slackStandardEmojiNames = []string{",
    ]
    for name in sorted(names):
        lines.append("\t" + json.dumps(name) + ",")
    lines.append("}")
    lines.append("")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
